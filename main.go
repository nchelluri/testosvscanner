func main() {
	for range 5 {
		if err := query(); err != nil {
			log.Error().
				Err(err).
				Msg("Error performing OSV Query")
		}
		time.Sleep(30 * time.Second)
	}
}

func query() error {
	start := time.Now()
	log.Info().Msg("Starting query()...")

	obreq := osv.BatchedQuery{Queries: queries}
	obres, err := osv.MakeRequest(obreq)
	if err != nil {
		return fmt.Errorf("error making OSV batch request: %w", err)
	}

	if len(queries) != len(obres.Results) {
		return fmt.Errorf("number of OSV queries (unique purls) %d does not equal number of query results %d",
			len(queries), len(obres.Results))
	}

	log.Info().
		Int("reslen", len(obres.Results)).
		Msg("len(obres.Results)")

	sortedVids := make([][]string, 0, len(obres.Results))
	for i := range obres.Results {
		vulns := make([]string, 0, len(obres.Results[i].Vulns))
		for j := range obres.Results[i].Vulns {
			vulns = append(vulns, obres.Results[i].Vulns[j].ID)
		}
		slices.Sort(vulns)
		sortedVids = append(sortedVids, vulns)
	}

	label := "testosv-" + time.Now().Format(time.RFC3339)
	reqFile := label + "-req.txt"
	resFile := label + "-res.txt"
	sortedVidsFile := label + "-sorted-vids.txt"

	if err := writeJSON(reqFile, obreq); err != nil {
		return err
	}

	if err := writeJSON(resFile, obres); err != nil {
		return err
	}

	if err := writeJSON(sortedVidsFile, sortedVids); err != nil {
		return err
	}

	log.Info().
		Dur("duration_ms", time.Since(start)).
		Msg("Finished query().")

	return nil
}

func writeJSON(filename string, v any) error {
	b, err := json.Marshal(v)
	if err != nil {
		return fmt.Errorf("error marshaling %s JSON: %w", filename, err)
	}
	if err := os.WriteFile(filename, b, 0700); err != nil {
		return fmt.Errorf("error writing %s file: %w", filename, err)
	}

	return nil
}

